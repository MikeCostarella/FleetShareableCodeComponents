// Regenerates address-lookup/src/parcelsApps.js from the Statehouse fleet
// manifest: one entry per `county-parcels` repo, keyed by county FIPS.
//
//   cd C:\projects\FleetShareableCodeComponents
//   npm run build:parcels-apps
//
// Run it whenever a parcels app is added, renamed or moved, then bump
// address-lookup/src/VERSION and sync. The manifest is read from the sibling
// Statehouse checkout (override with STATEHOUSE_MANIFEST=<path>).

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, "..", "..");
const manifestPath =
  process.env.STATEHOUSE_MANIFEST ??
  path.resolve(repoRoot, "..", "Statehouse", "data", "repos.manifest.json");
const outPath = path.resolve(here, "..", "src", "parcelsApps.js");

const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
const rows = manifest.repos
  .filter((r) => r.category === "county-parcels")
  .map((r) => {
    if (!/^39\d{3}$/.test(r.countyFips ?? "")) throw new Error(`${r.name}: bad countyFips ${r.countyFips}`);
    if (!r.county) throw new Error(`${r.name}: no county`);
    if (!/^https:\/\/.+\/$/.test(r.pagesUrl ?? "")) throw new Error(`${r.name}: bad pagesUrl ${r.pagesUrl}`);
    return { fips: r.countyFips, county: r.county, url: r.pagesUrl };
  })
  .sort((a, b) => a.fips.localeCompare(b.fips));

const seen = new Set();
for (const r of rows) {
  if (seen.has(r.fips)) throw new Error(`two parcels apps for FIPS ${r.fips}`);
  seen.add(r.fips);
}

const body = rows
  .map((r) => `  "${r.fips}": { county: ${JSON.stringify(r.county)}, url: ${JSON.stringify(r.url)} },`)
  .join("\n");

writeFileSync(
  outPath,
  `// GENERATED by address-lookup/scripts/build-parcels-apps.mjs from the Statehouse
// fleet manifest (${rows.length} county-parcels repos). Do not edit by hand; rerun it.

/** County FIPS -> that county's parcels app. */
export const PARCELS_APPS = {
${body}
};
`,
);
console.log(`wrote ${outPath} (${rows.length} counties)`);
